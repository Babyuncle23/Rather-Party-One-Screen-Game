const EN_BASE = {
  COLORS: SIMPLE_COLORS, MATERIALS: SIMPLE_MATERIALS, MOODS: SIMPLE_MOODS,
  ERAS: SIMPLE_ERAS, COUNTRIES: SIMPLE_COUNTRIES, CITIES: SIMPLE_CITIES,
  FOODS: SIMPLE_FOODS, SPORTS: SIMPLE_SPORTS, PROFESSIONS: SIMPLE_PROFESSIONS,
  VEGETABLES: SIMPLE_VEGETABLES, FRUITS: SIMPLE_FRUITS, CLOTHES: SIMPLE_CLOTHES
};

export function getNerfVocab(locale) {
  const extra = NERF_SETS[locale] || {};
  const merged = {};
  for (const key of Object.keys(EN_BASE)) {
    merged[key] = extra[key] ? EN_BASE[key].concat(extra[key]) : EN_BASE[key];
  }
  return merged;
}